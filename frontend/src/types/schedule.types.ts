/**
 * Представляє окремий рейс автобуса в межах одного напрямку.
 */
export interface BusTrip {
  /** Унікальний ідентифікатор рейсу. */
  id: number;
  /** Час відправлення рейсу (наприклад, у форматі "HH:mm"). */
  time: string;
  /** Додаткова примітка до рейсу (наприклад, особливості маршруту або святкові дні). */
  note?: string | null;
  /** * Вказує, чи є рейс скороченим.
   * `true`, якщо автобус іде за скороченим маршрутом.
   */
  is_short?: boolean | null;
}

/**
 * Описує конкретний напрямок руху автобуса та список відповідних рейсів.
 */
export interface BusDirection {
  /** Унікальний ідентифікатор напрямку. */
  id: number;
  /** Назва кінцевої точки або опис напрямку (наприклад, "До вокзалу"). */
  endpoint_name: string;
  /** Масив рейсів, що належать до цього напрямку. */
  trips: BusTrip[];
}

/**
 * Основний інтерфейс маршруту, що містить ідентифікаційні дані та повний розклад.
 */
export interface Route {
  /** Внутрішній числовий ідентифікатор маршруту. */
  id: number;
  /** Унікальний ідентифікатор документа (часто використовується в CMS, наприклад Strapi). */
  documentId: string;
  /** Номер маршруту (наприклад, "42", "10A"). */
  number: string;
  /** Офіційна або повна назва маршруту. */
  title: string;
  /** Повний розклад руху, розділений за напрямками. */
  schedule: BusDirection[];
}
