async function getOrCreateStop(name, note) {
  // Шукаємо існуючу зупинку за назвою
  const existing = await strapiGet(
    "stops",
    `?filters[name][$eq]=${encodeURIComponent(name)}&pagination[pageSize]=1`,
  );

  if (existing.data.length > 0) {
    console.log(`  ✓ Зупинка вже є: "${name}"`);
    return existing.data[0].documentId;
  }

  // Створюємо нову
  const created = await strapiPost("stops", { name, note });
  console.log(`  + Створено зупинку: "${name}"`);
  return created.documentId;
}

async function getRouteDocumentId(number) {
  const res = await strapiGet(
    "routes",
    `?filters[number][$eq]=${number}&pagination[pageSize]=1`,
  );
  if (res.data.length === 0) {
    throw new Error(
      `Маршрут №${number} не знайдено в Strapi! Спочатку створи його в адмінці.`,
    );
  }
  return res.data[0].documentId;
}

