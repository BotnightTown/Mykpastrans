function parseStop(raw) {
  if (typeof raw === "string")
    return { name: raw, note: null, onDemand: false };
  return {
    name: raw.name,
    note: raw.note ?? null,
    onDemand: raw.onDemand ?? false,
  };
}

async function strapiPost(endpoint, data) {
  const res = await fetch(`${STRAPI_URL}/api/${endpoint}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ data }),
  });
  const json = await res.json();
  if (!res.ok) {
    throw new Error(
      `POST /api/${endpoint} failed: ${JSON.stringify(json.error)}`,
    );
  }
  return json.data;
}

async function strapiGet(endpoint, params = "") {
  const res = await fetch(`${STRAPI_URL}/api/${endpoint}${params}`);
  const json = await res.json();
  if (!res.ok) throw new Error(`GET /api/${endpoint} failed`);
  return json;
}

